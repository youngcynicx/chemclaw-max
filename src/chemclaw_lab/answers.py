"""S05 answer builder: deterministic claims with verifiable citations.

Answers are generated by deterministic rules over the SAME structured
snapshot the machine JSON exposes — the human rendering and the JSON are
two views of one result (§11.3/§11.4). No model is involved at this stage
(real-model answering lands in S06); every claim must either cite a
structured field or be explicitly unknown.

Claim kinds (§11.9):
- ``reported_fact``: a value read from a structured record at a specific
  revision, with field pointer and evidence refs.
- ``derived``: computed from other claims; the formula and inputs are
  recorded. Derived values are never stored as wet-lab observations.
- ``interpretation``: only what the record itself marks as an
  interpretation — never inferred by the builder.

Two SEPARATE verification layers per claim (§11.9):
- ``ref_opens``: every evidence ref points to a block that exists in the
  page's active transcript (the citation can be opened).
- ``value_matches``: the claimed number/unit/identity equals the
  structured record's value (the source actually supports it). A similar
  fragment is NOT support — the §17 scenario (fragment says 130 °C, answer
  claims 150 °C) fails verification and becomes a gap, never an answer.

Usage semantics for amounts (§11.4): plan/recipe amounts, actual
withdrawals and estimates are labelled distinctly and never conflated.
"""

from __future__ import annotations

import json
import re
from decimal import Decimal, InvalidOperation
from typing import Any

from . import query
from .auth import PrincipalContext
from .units import (
    UNIT_DIMENSIONS,
    convert_amount,
    display_unit,
    normalize_unit,
)

__all__ = ["AnswerError", "build_answer", "render_text"]


class AnswerError(Exception):
    def __init__(self, code: str, message: str, *, http_status: int = 400) -> None:
        super().__init__(message)
        self.code = code
        self.message = message
        self.http_status = http_status


_AMOUNT_RE = re.compile(r"(\d+(?:\.\d+)?)\s*(g|mg|ug|µg|mL|uL|µL|L|mol|mmol)\b")
_TEMP_RE = re.compile(r"(\d+(?:\.\d+)?)\s*(?:°C|degC)")
_SAMPLE_RE = re.compile(r"\b([A-Z]{1,3}[-\s]?\d{1,4})\b")

_USAGE_BY_MODALITY = {
    "plan": "计划/配方用量（未执行）",
    "operation": "实际取用",
    "measurement": "测量值",
    "observation": "观察记录",
    "negation": "已否定/划掉",
    "interpretation": "记录中的解释",
    "computed": "计算值（非湿实验观测）",
}

_FIELD_LABELS = {
    "amount": "用量",
    "unit": "单位",
    "operation": "操作",
    "observed_state": "观察状态",
    "measurement_value": "测量值",
    "performed_at": "时间",
    "sample_label": "样品",
    "plan_action": "计划动作",
}


def _new_id(prefix: str) -> str:
    import uuid

    return f"{prefix}_{uuid.uuid4().hex[:20]}"


def _refs_open(conn, refs: list[dict[str, Any]]) -> bool:
    """Check #1: every citation opens the EXACT preserved source block.

    Historical blocks remain addressable after a transcript revision; this
    check therefore does not require the block to belong to the current
    active run. It only proves the pointer resolves to a stored source.
    """
    if not refs:
        return False
    for ref in refs:
        page_id = ref.get("page_id")
        block_id = ref.get("block_id")
        if not page_id or not block_id:
            return False
        row = conn.execute(
            """
            SELECT rb.block_id
            FROM transcript_blocks rb
            JOIN transcript_runs rr ON rr.run_id = rb.run_id
            WHERE rr.page_id = ? AND rr.status = 'succeeded'
              AND rb.block_id = ?
            """,
            (page_id, block_id),
        ).fetchone()
        if row is None:
            return False
    return True


def _ref_text(conn, refs: list[dict[str, Any]]) -> str:
    chunks: list[str] = []
    for ref in refs or []:
        row = conn.execute(
            "SELECT block_json FROM transcript_blocks WHERE block_id = ?",
            (ref.get("block_id"),),
        ).fetchone()
        if row is not None:
            try:
                chunks.append(str(json.loads(row["block_json"] or "{}").get("text") or ""))
            except ValueError:
                continue
    return "\n".join(chunks)


_NUM_UNIT_RE = re.compile(
    r"(?P<value>\d+(?:\.\d+)?)\s*"
    r"(?P<unit>mg|g|kg|µg|ug|mL|ml|µL|uL|L|mmol|mol|°C|degC)\b",
    re.IGNORECASE,
)


def _source_supports(
    conn,
    claim: dict[str, Any],
    *,
    raw_text: str | None,
    provenance: dict[str, Any] | None = None,
) -> tuple[bool, str]:
    """Check #3: does the bound source actually support this assertion?

    Numbers in a different dimension never support the claim. A later human
    correction statement is a ``human_report`` source, not a physical
    observation witnessed by the system.
    """
    value = claim.get("value")
    unit = claim.get("unit")
    text = _ref_text(conn, claim.get("evidence_refs") or [])
    if isinstance(value, (int, float)) and unit:
        expected_unit = normalize_unit(str(unit))
        if str(unit).lower() in ("degc", "°c"):
            expected_unit = "degC"
        for match in _NUM_UNIT_RE.finditer(text):
            try:
                if abs(float(match.group("value")) - float(value)) > 1e-9:
                    continue
            except ValueError:
                continue
            raw_found = match.group("unit")
            found_unit = (
                "degC" if raw_found.lower() in ("degc", "°c")
                else normalize_unit(raw_found)
            )
            if expected_unit is None or found_unit == expected_unit:
                return True, "source_text"
        # Correction revisions may carry a human statement rather than a new
        # photo. The statement supports only if it explicitly contains the
        # corrected value; approval alone is not evidence.
        correction = (provenance or {}).get("correction_source")
        statement = json.dumps(
            {
                "reason": (provenance or {}).get("reason"),
                "correction_source": correction,
            },
            ensure_ascii=False,
        )
        for match in _NUM_UNIT_RE.finditer(statement):
            if abs(float(match.group("value")) - float(value)) <= 1e-9:
                found_unit = normalize_unit(match.group("unit"))
                if expected_unit is None or found_unit == expected_unit:
                    return True, "human_report"
        return False, "source_does_not_support_value"
    if isinstance(value, str) and value.strip():
        needle = value.strip().lower()
        if needle in text.lower() or needle in str(raw_text or "").lower():
            return True, "source_text"
        return False, "source_does_not_support_text"
    return False, "no_assertion"


def _decode_amount(field: dict[str, Any], name: str) -> tuple[Any, str | None, str | None]:
    """Decode every published amount/unit shape without guessing.

    Returns ``(value, display_unit, normalized_unit)``. Conflict between an
    amount-embedded unit and the top-level unit is surfaced as ``None`` unit
    (and therefore cannot be aggregated).
    """
    entry = field.get(name)
    top_unit = field.get("unit")
    if isinstance(top_unit, dict):
        top_unit = top_unit.get("normalized") or top_unit.get("raw")
    top_normalized = normalize_unit(top_unit) if isinstance(top_unit, str) else None
    if isinstance(entry, dict):
        value = entry.get("normalized")
        embedded = entry.get("unit")
        if isinstance(embedded, dict):
            embedded = embedded.get("normalized") or embedded.get("raw")
        embedded_normalized = normalize_unit(embedded) if isinstance(embedded, str) else None
        if embedded_normalized and top_normalized and embedded_normalized != top_normalized:
            return value, None, None
        unit = embedded_normalized or top_normalized
    else:
        value = entry
        unit = top_normalized
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        return None, None, None
    return value, display_unit(unit), unit


def _usage_semantics(field: dict[str, Any], event_kind: str) -> str:
    if field.get("uncertain"):
        return "估计/不确定（未确认）"
    return _USAGE_BY_MODALITY.get(event_kind, event_kind)


def _fact_claim(
    conn,
    cand: dict[str, Any],
    field_name: str,
    value: Any,
    unit: str | None = None,
    *,
    normalized_unit: str | None = None,
) -> dict[str, Any] | None:
    payload = cand["payload"]
    field = payload["fields"]
    if value is None:
        return None
    event_kind = field.get("event_kind") or "observation"
    statement_parts = []
    sample_label = field.get("sample_label")
    if sample_label:
        statement_parts.append(f"样品 {sample_label}")
    usage = _usage_semantics(field, event_kind)
    label = _FIELD_LABELS.get(field_name, field_name)
    if field_name in ("amount", "measurement_value") and unit:
        statement_parts.append(f"{label} {value} {unit}（{usage}）")
    elif field_name == "unit":
        statement_parts.append(f"单位 {value}（{usage}）")
    else:
        statement_parts.append(f"{label} {value}（{usage}）")
    claim = {
        "claim_id": _new_id("clm"),
        "kind": "reported_fact",
        "object_type": "experiment_event",
        "object_id": cand["object_id"],
        "revision": cand["revision"],
        "field_pointer": f"fields.{field_name}",
        "value": value,
        "unit": unit,
        "normalized_unit": normalized_unit,
        "modality": event_kind,
        "usage_semantics": usage,
        "statement": " ".join(statement_parts),
        "evidence_refs": payload.get("evidence_refs", []),
        "verify": {},
    }
    provenance: dict[str, Any] = {}
    try:
        provenance = json.loads(payload.get("provenance_json") or "{}")
    except (TypeError, ValueError):
        provenance = {}
    ref_opens = _refs_open(conn, claim["evidence_refs"])
    source_supports, support_kind = _source_supports(
        conn,
        claim,
        raw_text=payload.get("fields", {}).get("raw_text"),
        provenance=provenance,
    )
    # Three independent checks (§R07). ``field_matches`` only says the value
    # was copied from the structured field; it NEVER implies source support.
    claim["verify"] = {
        "ref_opens": ref_opens,
        "field_matches": True,
        "source_supports": bool(source_supports),
        "support_kind": support_kind,
        # Backwards-compatible aggregate: true only when the source supports.
        "value_matches": bool(ref_opens and source_supports),
    }
    return claim


def _extract_assertions(question: str) -> list[tuple[float, str]]:
    """Numbers the QUESTION asserts (°C plus amount units) — these must be
    checked against structured records, never accepted from similarity."""
    assertions: list[tuple[float, str]] = []
    for m in _TEMP_RE.finditer(question):
        assertions.append((float(m.group(1)), "degC"))
    for m in _AMOUNT_RE.finditer(question):
        unit = m.group(2).replace("µ", "u")
        assertions.append((float(m.group(1)), unit))
    return assertions


def _event_matches_assertion(field: dict[str, Any], value: float, unit: str) -> bool:
    inner = field.get("fields", {}) or {}
    candidates: list[tuple[float, str | None]] = []
    for name in ("amount", "measurement_value"):
        decoded, _shown, normalized = _decode_amount(inner, name)
        if decoded is not None:
            candidates.append((float(decoded), normalized))
    temp = inner.get("temperature")
    if isinstance(temp, (int, float)):
        candidates.append((float(temp), "degC"))
    expected = normalize_unit(unit)
    if unit.lower() in ("degc", "°c"):
        expected = "degC"
    for ev_value, ev_unit in candidates:
        if abs(ev_value - value) < 1e-9 and ev_unit == expected:
            return True
    return False


def build_answer(
    conn,
    context: PrincipalContext,
    question: str,
    *,
    project_ids: list[str] | None = None,
    knowledge_as_of: str | None = None,
) -> dict[str, Any]:
    if not isinstance(question, str) or not question.strip():
        raise AnswerError("schema_violation", "question must be a non-empty string.")
    question = question.strip()
    search_result = query.search(
        conn, context,
        project_ids=project_ids,
        sample_label=(m.group(1).replace(" ", "-") if (m := _SAMPLE_RE.search(question)) else None),
        text=question,
        knowledge_as_of=knowledge_as_of,
    )
    candidates = search_result["candidates"]
    event_candidates = [c for c in candidates if c["object_type"] == "experiment_event"]

    claims: list[dict[str, Any]] = []
    gaps: list[dict[str, Any]] = []
    assertions = _extract_assertions(question)

    for cand in event_candidates:
        payload = cand["payload"]
        field = payload["fields"].get("fields", {}) or {}
        raw_field = payload["fields"]
        # Numerical facts: amount / measurement value with unit semantics.
        # Decode the publish-format variants (amount.unit, fields.unit dict,
        # legacy scalar) through ONE decoder; a conflicting/missing unit stays
        # unit-less and is never invented.
        for name in ("amount", "measurement_value"):
            value, shown_unit, normalized_unit = _decode_amount(field, name)
            if value is not None:
                claim = _fact_claim(
                    conn, cand, name, value,
                    unit=shown_unit, normalized_unit=normalized_unit,
                )
                if claim:
                    claims.append(claim)
        # Temperature / other scalar fields stored flat.
        if isinstance(field.get("temperature"), (int, float)):
            claim = _fact_claim(conn, cand, "temperature", field["temperature"], unit="degC")
            if claim:
                claims.append(claim)
        # Status/state facts.
        for name in ("operation", "observed_state", "plan_action", "performed_at"):
            value = field.get(name)
            if isinstance(value, str) and value.strip():
                claim = _fact_claim(conn, cand, name, value)
                if claim:
                    claims.append(claim)
        # Interpretation claims ONLY from records explicitly marked so.
        if raw_field.get("event_kind") == "interpretation":
            claim = _fact_claim(conn, cand, "observed_state", raw_field.get("raw_text"))
            if claim:
                claim["kind"] = "interpretation"
                claims.append(claim)

    # Assertion coverage across ALL returned events: an asserted number that
    # no structured event supports is a gap (§17: 130 °C fragment vs 150 °C claim).
    supported_assertions: set[tuple[float, str]] = set()
    for cand in event_candidates:
        payload = cand["payload"]
        for value, unit in assertions:
            if _event_matches_assertion(payload["fields"], value, unit):
                supported_assertions.add((value, unit))
    for value, unit in assertions:
        if (value, unit) not in supported_assertions:
            gaps.append(
                {
                    "gap_id": _new_id("gap"),
                    "kind": "assertion_unsupported",
                    "asserted": {"value": value, "unit": unit},
                    "reason": (
                        "No structured record in scope supports this asserted "
                        "value; similar text fragments are not support."
                    ),
                }
            )

    # Derived claims: sum of ACTUAL amounts, but only within one explicit
    # dimension and one material identity (§R05/F07). Units are converted
    # with a recorded rule; missing/mixed dimensions are refused, never
    # silently added as 0.5 + 2 = 2.5.
    by_group: dict[tuple[str, str, str], list[dict[str, Any]]] = {}
    missing_unit_claims: list[dict[str, Any]] = []
    sample_dimensions: dict[str, set[str]] = {}
    sample_materials: dict[str, set[str]] = {}
    for claim in claims:
        if claim["kind"] != "reported_fact" or claim["field_pointer"] != "fields.amount":
            continue
        if claim["usage_semantics"] != "实际取用":
            continue
        event = next(
            (c for c in event_candidates if c["object_id"] == claim["object_id"]), None
        )
        if event is None:
            continue
        payload_fields = event["payload"]["fields"].get("fields", {}) or {}
        sample_id = event["payload"]["fields"].get("sample_id")
        unit = claim.get("normalized_unit")
        if not sample_id:
            continue
        if unit is None or unit not in UNIT_DIMENSIONS:
            missing_unit_claims.append(claim)
            continue
        dimension = UNIT_DIMENSIONS[unit][0]
        material = str(
            payload_fields.get("material_id")
            or payload_fields.get("chemical_id")
            or payload_fields.get("item_name")
            or payload_fields.get("material")
            or "unspecified"
        )
        sample_dimensions.setdefault(sample_id, set()).add(dimension)
        sample_materials.setdefault(sample_id, set()).add(material)
        by_group.setdefault((sample_id, material, dimension), []).append(claim)

    for claim in missing_unit_claims:
        gaps.append(
            {
                "gap_id": _new_id("gap"),
                "kind": "missing_unit",
                "claim_id": claim["claim_id"],
                "reason": (
                    "用量缺少可确定的单位，不能生成合计；该项单独保留为缺单位记录。"
                ),
            }
        )
    for sample_id, dims in sample_dimensions.items():
        if len(dims) > 1:
            gaps.append(
                {
                    "gap_id": _new_id("gap"),
                    "kind": "dimension_mismatch",
                    "sample_id": sample_id,
                    "dimensions": sorted(dims),
                    "reason": (
                        "同一记录含不同量纲的用量（如质量与体积），不能直接相加；"
                        "已按量纲分别列出。"
                    ),
                }
            )
    for sample_id, materials in sample_materials.items():
        if len(materials) > 1:
            gaps.append(
                {
                    "gap_id": _new_id("gap"),
                    "kind": "material_separated",
                    "sample_id": sample_id,
                    "materials": sorted(materials),
                    "reason": "不同物料的用量默认分别列出，不合并为一个物料总量。",
                }
            )

    target_unit = {"mass": "g", "volume": "ml", "amount_of_substance": "mol"}
    for (sample_id, material, dimension), group in by_group.items():
        if len(group) < 2:
            continue
        target = target_unit.get(dimension)
        if target is None:
            continue
        converted: list[dict[str, Any]] = []
        total = Decimal("0")
        for claim in group:
            try:
                value = Decimal(str(claim["value"]))
            except (InvalidOperation, ValueError):
                gaps.append(
                    {
                        "gap_id": _new_id("gap"),
                        "kind": "invalid_quantity",
                        "claim_id": claim["claim_id"],
                        "reason": "数值无法稳定序列化为十进制，未参与合计。",
                    }
                )
                continue
            factor = Decimal(str(UNIT_DIMENSIONS[claim["normalized_unit"]][1])) / Decimal(
                str(UNIT_DIMENSIONS[target][1])
            )
            total += value * factor
            converted.append(
                {
                    "claim_id": claim["claim_id"],
                    "value": claim["value"],
                    "unit": claim["unit"],
                    "normalized_unit": claim["normalized_unit"],
                    "conversion_rule": f"{claim['normalized_unit']}→{target} ×{factor}",
                }
            )
        if len(converted) < 2:
            continue
        shown_total = float(total)
        material_label = "" if material == "unspecified" else f"（物料 {material}）"
        claims.append(
            {
                "claim_id": _new_id("clm"),
                "kind": "derived",
                "object_type": "sample",
                "object_id": sample_id,
                "revision": max(c["revision"] for c in group),
                "field_pointer": None,
                "value": shown_total,
                "unit": display_unit(target),
                "normalized_unit": target,
                "dimension": dimension,
                "material": material,
                "formula": (
                    "sum(convert(amount, normalized_unit -> "
                    f"{target}, unit_rule_version=1)) where usage=实际取用 "
                    "and material and dimension match"
                ),
                "inputs": [c["claim_id"] for c in group],
                "conversion_inputs": converted,
                "statement": (
                    f"样品 {sample_id}{material_label} 实际取用合计 "
                    f"{round(shown_total, 9)} {display_unit(target)}（派生值，"
                    f"非湿实验观测；量纲={dimension}）。"
                ),
                "evidence_refs": [],
                "verify": {
                    "ref_opens": True,
                    "field_matches": True,
                    "source_supports": all(
                        c["verify"].get("source_supports") for c in group
                    ),
                    "support_kind": "derived_conversion",
                    "value_matches": all(
                        c["verify"].get("source_supports") for c in group
                    ),
                },
            }
        )

    # Sample identity facts from candidate payloads.
    seen_samples: set[str] = set()
    for cand in event_candidates:
        sample_label = cand["payload"]["fields"].get("sample_label")
        sample_id = cand["payload"]["fields"].get("sample_id")
        if sample_id and sample_label and sample_id not in seen_samples:
            seen_samples.add(sample_id)
            claims.append(
                {
                    "claim_id": _new_id("clm"),
                    "kind": "reported_fact",
                    "object_type": "sample",
                    "object_id": sample_id,
                    "revision": cand["revision"],
                    "field_pointer": "fields.sample_label",
                    "value": sample_label,
                    "unit": None,
                    "modality": cand["payload"]["fields"].get("event_kind"),
                    "usage_semantics": "样品身份",
                    "statement": f"样品编号 {sample_label} 对应记录样品 {sample_id}。",
                    "evidence_refs": cand["payload"].get("evidence_refs", []),
                    "verify": {
                        "ref_opens": _refs_open(
                            conn, cand["payload"].get("evidence_refs", [])
                        ),
                        "field_matches": True,
                        "source_supports": _source_supports(
                            conn,
                            {
                                "value": sample_label,
                                "unit": None,
                                "evidence_refs": cand["payload"].get("evidence_refs", []),
                            },
                            raw_text=cand["payload"]["fields"].get("raw_text"),
                        )[0],
                        "support_kind": "sample_identity",
                        "value_matches": (
                            _refs_open(conn, cand["payload"].get("evidence_refs", []))
                            and _source_supports(
                                conn,
                                {
                                    "value": sample_label,
                                    "unit": None,
                                    "evidence_refs": cand["payload"].get("evidence_refs", []),
                                },
                                raw_text=cand["payload"]["fields"].get("raw_text"),
                            )[0]
                        ),
                    },
                }
            )

    # Status: the question's own assertions decide. When the question asserts
    # values that NO structured record supports (§17: fragment says 130 °C,
    # question claims 150 °C), the answer cannot be "answered" — it is
    # unknown with the facts it did find attached as context.
    has_unsupported_assertion = any(
        g["kind"] == "assertion_unsupported" for g in gaps
    )
    unsupported_claims = [
        c for c in claims
        if c.get("kind") in ("reported_fact", "derived")
        and not (c.get("verify") or {}).get("source_supports")
    ]
    for claim in unsupported_claims:
        gaps.append(
            {
                "gap_id": _new_id("gap"),
                "kind": "claim_unsupported",
                "claim_id": claim["claim_id"],
                "reason": (
                    "该断言所绑定的来源不能支持其数值/单位；已降级为待核对，"
                    "不得作为已证实事实渲染。"
                ),
            }
        )
    if not claims:
        status = "unknown"
    elif has_unsupported_assertion:
        status = "unknown"
    elif unsupported_claims:
        supported = [c for c in claims if c not in unsupported_claims]
        status = "partial" if supported else "needs_review"
    else:
        status = "answered"
    if not claims and not gaps:
        gaps.append(
            {
                "gap_id": _new_id("gap"),
                "kind": "insufficient_records",
                "reason": "No structured records in scope match the question.",
            }
        )
    answer = {
        "question": question,
        "snapshot_version": search_result["snapshot_version"],
        "scope": search_result["scope"],
        "status": status,
        "claims": claims,
        "gaps": gaps,
        "pending_corrections": search_result["pending_corrections"],
        "vector_enabled": False,
    }
    answer["rendered_text"] = render_text(answer)
    return answer


def render_text(answer: dict[str, Any]) -> str:
    """Human rendering generated from the SAME structured result (§11.3):
    every sentence cites its claim id; gaps and pending corrections are
    rendered too. Nothing is invented here."""
    lines: list[str] = []
    header = f"[snapshot {answer['snapshot_version']}]"
    claims = answer.get("claims", [])
    status = answer.get("status")
    if status == "unknown" or not claims:
        lines.append(f"{header} 依据不足：无法给出有引用的回答（unknown）。")
    elif status == "needs_review":
        lines.append(f"{header} 关键来源不能支持断言：以下内容需要人工核对（needs_review）。")
    elif status == "partial":
        lines.append(f"{header} 部分内容有来源支持，其余项需要核对（partial）。")
    for claim in claims:
        supported = (claim.get("verify") or {}).get("source_supports", True)
        prefix = "" if supported else "（待核对）"
        if claim["kind"] == "reported_fact":
            lines.append(f"{header} {prefix}{claim['statement']} [{claim['claim_id']}]")
        elif claim["kind"] == "derived":
            lines.append(
                f"{header} {prefix}{claim['statement']} "
                f"[derived from {', '.join(claim['inputs'])}]"
            )
        else:
            lines.append(
                f"{header}（记录中的解释）{prefix}{claim['statement']} [{claim['claim_id']}]"
            )
    for gap in answer.get("gaps", []):
        if gap["kind"] == "assertion_unsupported":
            asserted = gap["asserted"]
            lines.append(
                f"{header} 缺口：断言 {asserted['value']} {asserted['unit']} "
                f"无结构化记录支持。[{gap['gap_id']}]"
            )
        else:
            lines.append(f"{header} 缺口：{gap['reason']} [{gap['gap_id']}]")
    for pending in answer.get("pending_corrections", []):
        lines.append(
            f"{header} 注意：事件 {pending['event_id']} 在快照之后已有更正"
            f"（revision {pending['current_revision']}），未并入本回答。"
        )
    return "\n".join(lines)
